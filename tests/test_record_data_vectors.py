"""Record data validation against catalog-generated models.

The interop record-data vectors validate concrete record data against the
example.lexicon.record schema in the catalog. Models generated by
LexiconCatalog must accept every valid case and reject every invalid one.
"""

import json

import pytest

from fastatp.lex.schema import LexiconCatalog


@pytest.fixture(scope="module")
def catalog(interop_dir_module) -> LexiconCatalog:
    cat = LexiconCatalog()
    cat.add_directory(interop_dir_module / "lexicon" / "catalog")
    return cat


@pytest.fixture(scope="module")
def interop_dir_module():
    from tests.conftest import INTEROP

    if not INTEROP.is_dir():
        pytest.skip("reference/atproto-interop-tests not present")
    return INTEROP


def _cases(interop_dir, name):
    return json.loads((interop_dir / "lexicon" / name).read_text())


def test_record_data_valid(catalog, interop_dir_module):
    for case in _cases(interop_dir_module, "record-data-valid.json"):
        nsid = case["data"]["$type"]
        model = catalog.model_for(nsid)
        instance = model.from_json_dict(case["data"])
        assert instance is not None, case["name"]


def test_record_data_invalid(catalog, interop_dir_module):
    failures = []
    for case in _cases(interop_dir_module, "record-data-invalid.json"):
        nsid = case["data"]["$type"]
        model = catalog.model_for(nsid)
        try:
            model.from_json_dict(case["data"])
            failures.append(case["name"])
        except Exception:
            pass
    assert not failures, f"{len(failures)} invalid records accepted: {failures}"
